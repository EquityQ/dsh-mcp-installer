/**
 * Build the two runtime artifacts:
 *
 *   lib/index.js   Host half — ESM, Node platform, js-yaml bundled so the
 *                  plugin has no runtime dependency resolution of its own.
 *   lib/client.js  Client half — the browser module-loader factory format
 *                  (`window.__ModuleLoader__.load({ id, factory })`).
 *                  React and react/jsx-runtime stay external: the shell's
 *                  shared module table supplies them.
 *
 * Both halves are minified. The Host half keeps names and a version banner so
 * a stack trace still names the code that produced it; the Client half is
 * minified because it ships on every settings page load, and no source maps
 * are published (nobody debugs the shipped bundle, and they double its size).
 *
 * Run with `npm run build` (or `npm test`, which builds first).
 */
import { build } from 'esbuild';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(import.meta.url), '..', '..');
const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));

await mkdir(resolve(root, 'lib'), { recursive: true });

// ── Host half ──────────────────────────────────────────────────────────────
await build({
  absWorkingDir: root,
  entryPoints: ['src/index.ts'],
  outfile: 'lib/index.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  minify: true,
  // Keep names: the Host's messages and stack traces are the debugging surface
  // a user pastes into an issue, so `installIntoProfile` must survive minifying.
  keepNames: true,
  legalComments: 'none',
  logLevel: 'warning',
  banner: {
    js: `// ${pkg.name} ${pkg.version} — Host half. Generated by scripts/build.mjs; edit src/ instead.`,
  },
});

// ── Client half ────────────────────────────────────────────────────────────
const temporary = resolve(root, 'lib/.client.tmp.cjs');
await build({
  absWorkingDir: root,
  entryPoints: ['src/client/index.tsx'],
  outfile: temporary,
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'es2022',
  jsx: 'automatic',
  external: ['react', 'react/jsx-runtime'],
  minify: true,
  legalComments: 'none',
  logLevel: 'warning',
  define: { 'process.env.NODE_ENV': '"production"' },
});

const body = (await readFile(temporary, 'utf8')).replace(/^"use strict";\r?\n/, '');
const banner =
  `// ${pkg.name} ${pkg.version} — Client half, module-loader factory.\n` +
  '// Generated by scripts/build.mjs; edit src/client instead.\n' +
  'window.__ModuleLoader__.load({\n' +
  `\tid: ${JSON.stringify(pkg.name)},\n` +
  '\tfactory: (require) => {\n' +
  '\t\tvar module = { exports: {} };\n' +
  '\t\tvar exports = module.exports;\n' +
  '\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });\n';
const footer = '\n\t\treturn module.exports;\n\t},\n});\n';

await writeFile(resolve(root, 'lib/client.js'), `${banner}${body}${footer}`, 'utf8');
await rm(temporary, { force: true });

const [hostSize, clientSize] = await Promise.all([
  readFile(resolve(root, 'lib/index.js')).then((buffer) => buffer.length),
  readFile(resolve(root, 'lib/client.js')).then((buffer) => buffer.length),
]);
console.log(
  `built lib/index.js (${(hostSize / 1024).toFixed(1)} KiB) and ` +
    `lib/client.js (${(clientSize / 1024).toFixed(1)} KiB)`,
);
